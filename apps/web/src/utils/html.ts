export function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

export function renderIcon(iconClassName: string): string {
  return `<i class="${iconClassName} fa-fw" aria-hidden="true"></i>`;
}
